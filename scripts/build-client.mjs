// Writes lib/client.js, the browser bundle dsh-client-modules serves for this
// package, and lib/sounds.js, the clip catalogue generated from assets/*.wav.
//
// The browser loader resolves `require` only against modules registered through
// window.__ModuleLoader__.load, so the bundle registers the catalogue under the
// specifier src/client.js requires. The plugin module is registered first, so
// client-modules materializes it only after the catalogue registration of the
// same bundle is in place.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("..", import.meta.url);
const read = (path) => readFileSync(new URL(path, root), "utf8");

/** Event name from a clip file name: `assets/finish.wav` is the `finish` event. */
export function eventOf(file) {
	return file.replace(/\.wav$/, "");
}

/** Clip files in assets/, in name order. */
export function clipFiles() {
	return readdirSync(new URL("assets/", root)).filter((file) => file.endsWith(".wav")).sort();
}

/** The catalogue module with one data URL per clip filled into lib/sounds.js. */
export function buildCatalogue() {
	const source = read("lib/sounds.js");
	const lines = clipFiles().map((file) => {
		const base64 = readFileSync(new URL(`assets/${file}`, root)).toString("base64");
		return `\t${eventOf(file)}: "data:audio/wav;base64,${base64}",`;
	});
	const start = source.indexOf("export const CLIPS = {");
	const end = source.indexOf("};", start) + 2;
	const block = ["export const CLIPS = {", ...lines, "};"].join("\n");
	return source.slice(0, start) + block + source.slice(end);
}

/** The browser bundle: src/client.js plus the catalogue registration. */
export function buildClient() {
	const source = buildCatalogue();
	const names = [...source.matchAll(/^export (?:const|function) (\w+)/gm)].map((match) => match[1]);
	const body = source.replace(/^export (const|function) /gm, "$1 ");
	const indented = body.trimEnd().replace(/^(?=.)/gm, "\t\t");
	return `// Generated by scripts/build-client.mjs from src/client.js, lib/sounds.js and assets/*.wav; edit those instead.

${read("src/client.js")}
window.__ModuleLoader__.load({
	id: "dsh-finish-sound/lib/sounds.js",
	factory: () => {
${indented}
		return { ${names.join(", ")} };
	},
});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	writeFileSync(new URL("lib/sounds.js", root), buildCatalogue());
	writeFileSync(new URL("lib/client.js", root), buildClient());
}
